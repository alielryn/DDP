def persegi (sisi):
    return sisi*sisi

def persegi_panjang (p,l):
    return p*l

def segitiga (a,t):
    return 0.5*a*t

def lingkaran (r):
    return 3.14*r**2

def jajr_genjang (a,t):
    return a*t

print(persegi(4))
print(persegi_panjang(2,5))
print(segitiga(3,5))
print(lingkaran(6))
print(jajr_genjang(4,6))


